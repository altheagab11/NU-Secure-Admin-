    /**
     * @param  list<array{0: string, 1: string}>  $windows
     * @return Collection<int, array<string, mixed>>
     */
    protected function fetchVisitorRowsUsingWindows(array $windows): Collection
    {
        if ($windows === []) {
            return collect();
        }

        $query = DB::table('visit as v')
            ->leftJoin('visitor as vr', 'vr.visitor_id', '=', 'v.visitor_id')
            ->leftJoin('address as a', 'a.address_id', '=', 'vr.address_id')
            ->leftJoin('visit_type as vt', 'vt.visit_type_id', '=', 'v.visit_type_id')
            ->leftJoin('office as o', 'o.office_id', '=', 'v.primary_office_id')
            ->leftJoin('exit_status as es', 'es.exit_status_id', '=', 'v.exit_status_id')
            ->leftJoin('users as gu', 'gu.user_id', '=', 'v.guard_user_id')
            ->leftJoin('contractor as c', 'c.visit_id', '=', 'v.visit_id')
            ->whereNotNull('v.entry_time')
            ->where(function ($builder) use ($windows) {
                foreach ($windows as [$windowStart, $windowEnd]) {
                    $builder->orWhereBetween('v.entry_time', [$windowStart, $windowEnd]);
                }
            })
            ->orderBy('v.entry_time')
            ->orderBy('v.visit_id')
            ->select([
                'v.visit_id',
                'v.purpose_reason',
                'v.entry_time',
                'v.exit_time',
                'v.duration_minutes',
                'v.exit_status_id',
                'v.destination_text',
                'v.visit_type_id',
                'vr.control_number',
                'vr.first_name',
                'vr.last_name',
                'vr.birthday',
                'vr.contact_no',
                'vr.pass_number',
                'a.house_no',
                'a.street',
                'a.barangay',
                'a.city_municipality',
                'a.province',
                'a.region',
                'vt.visit_type_name',
                'o.office_name',
                'es.exit_status_name',
                'gu.first_name as guard_first_name',
                'gu.last_name as guard_last_name',
                'gu.role_id as guard_role_id',
                'c.contact_person as contractor_contact_person',
            ]);

        $visits = $query->get();

        return $this->mapVisitRows($visits);
    }

    /**
     * @param  Collection<int, object>|iterable<int, object>  $visits
     * @return Collection<int, array<string, mixed>>
     */
    protected function mapVisitRows(iterable $visits): Collection
    {
        $visits = collect($visits);
        $remarksByVisit = collect();
        $alertsByVisit = collect();
        $visitIds = $visits->pluck('visit_id')->filter()->values();

        if ($visitIds->isNotEmpty()) {
            $remarksByVisit = DB::table('office_scan')
                ->select(['visit_id', 'remarks', 'scan_time'])
                ->whereIn('visit_id', $visitIds)
                ->whereNotNull('remarks')
                ->whereRaw("TRIM(COALESCE(remarks, '')) <> ''")
                ->orderByDesc('scan_time')
                ->get()
                ->groupBy('visit_id')
                ->map(function ($group) {
                    return trim((string) ($group->first()->remarks ?? ''));
                });

            $alertsByVisit = DB::table('alerts')
                ->select(['visit_id', 'alert_type', 'created_at'])
                ->whereIn('visit_id', $visitIds)
                ->orderByDesc('created_at')
                ->get()
                ->groupBy('visit_id')
                ->map(function ($group) {
                    return trim((string) ($group->first()->alert_type ?? ''));
                });
        }

        return $visits->map(function ($row) use ($remarksByVisit, $alertsByVisit) {
            $visit = (array) $row;
            $visitId = $visit['visit_id'] ?? null;

            $firstName = trim((string) ($visit['first_name'] ?? ''));
            $lastName = trim((string) ($visit['last_name'] ?? ''));
            $fullName = trim($firstName.' '.$lastName);

            $entry = $this->parseDateTime($visit['entry_time'] ?? null);
            $exit = $this->parseDateTime($visit['exit_time'] ?? null);
            $birthday = $this->parseDateOnly($visit['birthday'] ?? null);
            $durationMinutes = $this->resolveDurationMinutes($visit, $entry, $exit);

            $officeOrPerson = $this->resolveOfficeOrPerson($visit);
            $status = $this->resolveVisitStatus($visit);
            $entryMethod = $this->resolveEntryMethod($visit);
            $processedBy = trim(((string) ($visit['guard_first_name'] ?? '')).' '.((string) ($visit['guard_last_name'] ?? '')));
            $remarks = (string) ($remarksByVisit->get($visitId, ''));
            $alertType = trim((string) ($alertsByVisit->get($visitId, '')));

            return [
                'visit_id' => $visitId !== null ? (string) $visitId : '',
                'control_number' => (string) ($visit['control_number'] ?? ''),
                'visitor_full_name' => $fullName,
                'birth_date' => $birthday,
                'address' => $this->formatAddress($visit),
                'contact_number' => (string) ($visit['contact_no'] ?? ''),
                'pass_number' => (string) ($visit['pass_number'] ?? ''),
                'visit_type' => (string) ($visit['visit_type_name'] ?? ''),
                'purpose_of_visit' => (string) ($visit['purpose_reason'] ?? ''),
                'office_or_person' => $officeOrPerson,
                'date_of_visit' => $entry ? $entry->copy()->startOfDay() : null,
                'time_in' => $entry,
                'time_out' => $exit,
                'duration' => $this->formatDurationLabel($durationMinutes),
                'visit_status' => $status,
                'entry_method' => $entryMethod,
                'processed_by' => $processedBy,
                'alert' => $alertType !== '' ? $alertType : 'None',
                'remarks' => $remarks,
            ];
        })->values();
    }

    /**
     * @param  Collection<int, array<string, mixed>>  $rows
     */
    protected function writeVisitorTable(Worksheet $sheet, Collection $rows, int $headerRow, string $lastColumn): void
    {
        $headers = [
            'A' => 'Visit ID',
            'B' => 'Control Number',
            'C' => 'Visitor Full Name',
            'D' => 'Birth Date',
            'E' => 'Address',
            'F' => 'Contact Number',
            'G' => 'Pass No.',
            'H' => 'Visit Type',
            'I' => 'Purpose of Visit',
            'J' => 'Office or Person to Visit',
            'K' => 'Date of Visit',
            'L' => 'Time In',
            'M' => 'Time Out',
            'N' => 'Duration',
            'O' => 'Visit Status',
            'P' => 'Entry Method',
            'Q' => 'Processed By',
            'R' => 'Alert',
            'S' => 'Remarks',
        ];

        foreach ($headers as $column => $label) {
            $sheet->setCellValue($column.$headerRow, $label);
        }

        $headerRange = 'A'.$headerRow.':'.$lastColumn.$headerRow;
        $sheet->getStyle($headerRange)->getFont()->setBold(true);
        $sheet->getStyle($headerRange)->getFill()
            ->setFillType(Fill::FILL_SOLID)
            ->getStartColor()->setRGB('243C96');
        $sheet->getStyle($headerRange)->getFont()->getColor()->setRGB('FFFFFF');
        $sheet->getStyle($headerRange)->getAlignment()
            ->setHorizontal(Alignment::HORIZONTAL_CENTER)
            ->setVertical(Alignment::VERTICAL_CENTER);

        $dataStart = $headerRow + 1;
        $currentRow = $dataStart;

        foreach ($rows as $row) {
            $this->writeTextCell($sheet, 'A'.$currentRow, (string) ($row['visit_id'] ?? ''));
            $this->writeTextCell($sheet, 'B'.$currentRow, (string) ($row['control_number'] ?? ''));
            $sheet->setCellValue('C'.$currentRow, (string) ($row['visitor_full_name'] ?? ''));

            if (($row['birth_date'] ?? null) instanceof Carbon) {
                $sheet->setCellValue('D'.$currentRow, ExcelDate::PHPToExcel($row['birth_date']));
                $sheet->getStyle('D'.$currentRow)->getNumberFormat()->setFormatCode('yyyy-mm-dd');
            } else {
                $sheet->setCellValue('D'.$currentRow, '');
            }

            $sheet->setCellValue('E'.$currentRow, (string) ($row['address'] ?? ''));
            $this->writeTextCell($sheet, 'F'.$currentRow, (string) ($row['contact_number'] ?? ''));
            $this->writeTextCell($sheet, 'G'.$currentRow, (string) ($row['pass_number'] ?? ''));
            $sheet->setCellValue('H'.$currentRow, (string) ($row['visit_type'] ?? ''));
            $sheet->setCellValue('I'.$currentRow, (string) ($row['purpose_of_visit'] ?? ''));
            $sheet->setCellValue('J'.$currentRow, (string) ($row['office_or_person'] ?? ''));

            if (($row['date_of_visit'] ?? null) instanceof Carbon) {
                $sheet->setCellValue('K'.$currentRow, ExcelDate::PHPToExcel($row['date_of_visit']));
                $sheet->getStyle('K'.$currentRow)->getNumberFormat()->setFormatCode('yyyy-mm-dd');
            } else {
                $sheet->setCellValue('K'.$currentRow, '');
            }

            if (($row['time_in'] ?? null) instanceof Carbon) {
                $sheet->setCellValue('L'.$currentRow, ExcelDate::PHPToExcel($row['time_in']));
                $sheet->getStyle('L'.$currentRow)->getNumberFormat()->setFormatCode('hh:mm:ss AM/PM');
            } else {
                $sheet->setCellValue('L'.$currentRow, '');
            }

            if (($row['time_out'] ?? null) instanceof Carbon) {
                $sheet->setCellValue('M'.$currentRow, ExcelDate::PHPToExcel($row['time_out']));
                $sheet->getStyle('M'.$currentRow)->getNumberFormat()->setFormatCode('hh:mm:ss AM/PM');
            } else {
                $sheet->setCellValue('M'.$currentRow, '');
            }

            $sheet->setCellValue('N'.$currentRow, (string) ($row['duration'] ?? ''));
            $sheet->setCellValue('O'.$currentRow, (string) ($row['visit_status'] ?? ''));
            $sheet->setCellValue('P'.$currentRow, (string) ($row['entry_method'] ?? ''));
            $sheet->setCellValue('Q'.$currentRow, (string) ($row['processed_by'] ?? ''));
            $sheet->setCellValue('R'.$currentRow, (string) ($row['alert'] ?? ''));
            $sheet->setCellValue('S'.$currentRow, (string) ($row['remarks'] ?? ''));

            $currentRow++;
        }

        $dataEnd = max($dataStart - 1, $currentRow - 1);
        $totalRow = $dataEnd + 2;
        $sheet->setCellValue('A'.$totalRow, 'Total Visitors:');
        $sheet->setCellValue('B'.$totalRow, $rows->count());
        $sheet->getStyle('A'.$totalRow.':B'.$totalRow)->getFont()->setBold(true);

        $sheet->setAutoFilter($headerRange);
        $sheet->freezePane('A'.($headerRow + 1));

        if ($dataEnd >= $headerRow) {
            $sheet->getStyle('A'.$headerRow.':'.$lastColumn.$dataEnd)->getBorders()->getAllBorders()
                ->setBorderStyle(Border::BORDER_THIN);
        }

        foreach (range('A', $lastColumn) as $column) {
            $sheet->getColumnDimension($column)->setAutoSize(true);
        }

        // Keep ID / contact / pass columns as text so leading zeros are preserved.
        $sheet->getStyle('A'.$dataStart.':A'.max($dataStart, $dataEnd))
            ->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_TEXT);
        $sheet->getStyle('B'.$dataStart.':B'.max($dataStart, $dataEnd))
            ->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_TEXT);
        $sheet->getStyle('F'.$dataStart.':F'.max($dataStart, $dataEnd))
            ->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_TEXT);
        $sheet->getStyle('G'.$dataStart.':G'.max($dataStart, $dataEnd))
            ->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_TEXT);
    }

    protected function writeExcelFile(Carbon $reportDate, Collection $rows, string $relativePath): string
    {
        $disk = Storage::disk(self::DISK);
        $directory = dirname($relativePath);

        if (! $disk->exists($directory) && ! $disk->makeDirectory($directory)) {
            throw new RuntimeException('Unable to create the secure report storage directory.');
        }

        $spreadsheet = $this->buildSpreadsheet($reportDate, $rows);
        $absolutePath = $disk->path($relativePath);

        $writer = new Xlsx($spreadsheet);
        $writer->save($absolutePath);
        $spreadsheet->disconnectWorksheets();
        unset($spreadsheet);

        return $absolutePath;
    }

    protected function writeDateRangeExcelFile(
        Carbon $startDate,
        Carbon $endDate,
        Collection $rows,
        string $relativePath,
        string $generatedByName
    ): string {
        $disk = Storage::disk(self::DISK);
        $directory = dirname($relativePath);

        if (! $disk->exists($directory) && ! $disk->makeDirectory($directory)) {
            throw new RuntimeException('Unable to create the secure report storage directory.');
        }

        $spreadsheet = $this->buildDateRangeSpreadsheet(
            $startDate,
            $endDate,
            $rows,
            $generatedByName,
            now('Asia/Manila')
        );
        $absolutePath = $disk->path($relativePath);

        $writer = new Xlsx($spreadsheet);
        $writer->save($absolutePath);
        $spreadsheet->disconnectWorksheets();
        unset($spreadsheet);

        return $absolutePath;
    }

    protected function writeTextCell(Worksheet $sheet, string $coordinate, string $value): void
    {
        $sheet->setCellValueExplicit($coordinate, $value, DataType::TYPE_STRING);
        $sheet->getStyle($coordinate)->getNumberFormat()->setFormatCode(NumberFormat::FORMAT_TEXT);
    }

    protected function parseCalendarDate(string|\DateTimeInterface $date, string $label): Carbon
    {
        try {
            if ($date instanceof \DateTimeInterface) {
                return Carbon::instance(\DateTimeImmutable::createFromInterface($date))
                    ->timezone('Asia/Manila')
                    ->startOfDay();
            }

            $raw = trim((string) $date);
            $parsed = Carbon::createFromFormat('Y-m-d', $raw, 'Asia/Manila');

            if (! $parsed || $parsed->format('Y-m-d') !== $raw) {
                throw new RuntimeException('Please select a '.$label.'.');
            }

            return $parsed->startOfDay();
        } catch (RuntimeException $e) {
            throw $e;
        } catch (Throwable $e) {
            throw new RuntimeException('Please select a '.$label.'.');
        }
    }

    protected function sanitizeDateToken(string $dateString): string
    {
        if (! preg_match('/^\d{4}-\d{2}-\d{2}$/', $dateString)) {
            throw new RuntimeException('Invalid date token for report file naming.');
        }

        return $dateString;
    }

    protected function sanitizeFileName(string $fileName): string
    {
        $base = basename(str_replace(['\\', '/'], DIRECTORY_SEPARATOR, $fileName));
        $base = preg_replace('/[^A-Za-z0-9._-]/', '', $base) ?? '';

        if ($base === '' || ! str_ends_with(strtolower($base), '.xlsx')) {
            throw new RuntimeException('Invalid report file name.');
        }

        return $base;
    }

    protected function resolveAdminDisplayName(User|int|null $adminUser): string
    {
        if ($adminUser instanceof User) {
            $name = trim(((string) ($adminUser->first_name ?? '')).' '.((string) ($adminUser->last_name ?? '')));

            if ($name !== '') {
                return $name;
            }

            return (string) ($adminUser->email ?? 'Admin');
        }

        if ($adminUser === null) {
            return 'Admin';
        }

        $user = User::query()->find($adminUser);
        if (! $user) {
            return 'Admin #'.$adminUser;
        }

        return $this->resolveAdminDisplayName($user);
    }

    protected function formatAddress(array $visit): string
    {
        $line1 = trim(((string) ($visit['house_no'] ?? '')).' '.((string) ($visit['street'] ?? '')));

        return collect([
            $line1,
            $visit['barangay'] ?? null,
            $visit['city_municipality'] ?? null,
            $visit['province'] ?? null,
            $visit['region'] ?? null,
        ])->map(fn ($value) => trim((string) $value))
            ->filter(fn ($value) => $value !== '')
            ->implode(', ');
    }

    protected function resolveOfficeOrPerson(array $visit): string
    {
        $office = trim((string) ($visit['office_name'] ?? ''));
        $destination = trim((string) ($visit['destination_text'] ?? ''));
        $contactPerson = trim((string) ($visit['contractor_contact_person'] ?? ''));

        $parts = collect([$office, $destination, $contactPerson])
            ->filter(fn ($value) => $value !== '')
            ->unique()
            ->values();

        return $parts->implode(' / ');
    }

    protected function resolveVisitStatus(array $visit): string
    {
        $exitStatus = trim((string) ($visit['exit_status_name'] ?? ''));
        if ($exitStatus !== '') {
            return $exitStatus;
        }

        if (filled($visit['exit_time'] ?? null)) {
            return 'Completed';
        }

        return 'Active';
    }

    protected function resolveEntryMethod(array $visit): string
    {
        $roleId = (int) ($visit['guard_role_id'] ?? 0);
        if ($roleId === 4) {
            return 'Self-Registration';
        }

        $visitType = trim((string) ($visit['visit_type_name'] ?? ''));
        if ($visitType !== '') {
            return 'Guard Registration ('.$visitType.')';
        }

        return $roleId > 0 ? 'Guard Registration' : '';
    }

    protected function resolveDurationMinutes(array $visit, ?Carbon $entry, ?Carbon $exit): int
    {
        if (! $entry) {
            return 0;
        }

        if (! $exit) {
            return max(0, $entry->diffInMinutes(Carbon::now('Asia/Manila')));
        }

        $fromColumn = $visit['duration_minutes'] ?? null;
        if (is_numeric($fromColumn)) {
            return max(0, (int) $fromColumn);
        }

        return max(0, $entry->diffInMinutes($exit));
    }

    protected function formatDurationLabel(int $minutes): string
    {
        if ($minutes < 60) {
            return $minutes.' mins';
        }

        $hours = intdiv($minutes, 60);
        $remaining = $minutes % 60;

        if ($remaining === 0) {
            return $hours.' hr'.($hours > 1 ? 's' : '');
        }

        return $hours.' hr '.$remaining.' mins';
    }

    protected function parseDateTime(mixed $value): ?Carbon
    {
        if (! filled($value)) {
            return null;
        }

        try {
            return Carbon::parse($value)->timezone('Asia/Manila');
        } catch (Throwable $e) {
            return null;
        }
    }

    protected function parseDateOnly(mixed $value): ?Carbon
    {
        if (! filled($value)) {
            return null;
        }

        try {
            return Carbon::parse($value)->timezone('Asia/Manila')->startOfDay();
        } catch (Throwable $e) {
            return null;
        }
    }

    protected function safeErrorMessage(Throwable $e): string
    {
        $message = trim($e->getMessage());

        if ($message === '') {
            return 'Report generation failed due to an unexpected error.';
        }

        // Keep message user-safe; avoid dumping paths/credentials.
        $message = preg_replace('/[A-Za-z]:\\\\[^\s]+/', '[path]', $message) ?? $message;
        $message = preg_replace('/\/(?:var|home|Users|storage)[^\s]+/', '[path]', $message) ?? $message;

        return mb_substr($message, 0, 500);
    }
