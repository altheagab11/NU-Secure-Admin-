    /**
     * Generate (or regenerate) the daily visitor Excel report for a calendar date.
     *
     * @param  string|\DateTimeInterface  $date  YYYY-MM-DD or date object (Asia/Manila calendar day)
     * @param  int|null  $generatedByUserId  Null when generated by scheduler/system
     * @param  bool  $regenerate  Replace an existing completed report
     */
    public function generate(string|\DateTimeInterface $date, ?int $generatedByUserId = null, bool $regenerate = false): DailyReport
    {
        $reportDate = $this->normalizeReportDate($date);
        $dateString = $reportDate->toDateString();
        $fileName = $this->buildFileName($dateString);
        $relativePath = $this->buildRelativePath($dateString, $fileName);

        $report = DailyReport::query()->firstOrNew([
            'report_date' => $dateString,
            'report_type' => self::REPORT_TYPE,
        ]);

        if (
            $report->exists
            && $report->generation_status === DailyReport::STATUS_COMPLETED
            && ! $regenerate
        ) {
            Log::info('Daily visitor report already exists; skipping duplicate generation.', [
                'report_date' => $dateString,
                'report_id' => $report->id,
                'action' => 'daily_report_duplicate_skipped',
            ]);

            return $report;
        }

        if ($report->exists && $report->generation_status === DailyReport::STATUS_GENERATING) {
            throw new RuntimeException('A report for this date is already being generated. Please wait and try again.');
        }

        $previousPath = $report->exists ? (string) $report->file_path : null;

        $report->fill([
            'date_range_end' => null,
            'file_name' => $fileName,
            'file_path' => $relativePath,
            'generation_status' => DailyReport::STATUS_GENERATING,
            'error_message' => null,
            'generated_by' => $generatedByUserId,
        ]);
        $report->save();

        try {
            $rows = $this->fetchVisitorRowsForDate($reportDate);
            $absolutePath = $this->writeExcelFile($reportDate, $rows, $relativePath);

            if (! is_file($absolutePath)) {
                throw new RuntimeException('The Excel report file could not be saved to secure storage.');
            }

            // Safely replace previous file when regenerating to a different path.
            if ($previousPath && $previousPath !== $relativePath && Storage::disk(self::DISK)->exists($previousPath)) {
                Storage::disk(self::DISK)->delete($previousPath);
            }

            $report->fill([
                'file_name' => $fileName,
                'file_path' => $relativePath,
                'record_count' => $rows->count(),
                'generation_status' => DailyReport::STATUS_COMPLETED,
                'generated_at' => now('Asia/Manila'),
                'generated_by' => $generatedByUserId,
                'error_message' => null,
            ]);
            $report->save();

            $action = $regenerate ? 'daily_report_regenerated' : (
                $generatedByUserId ? 'daily_report_manually_generated' : 'daily_report_automatically_generated'
            );

            Log::info('Daily visitor report generated successfully.', [
                'action' => $action,
                'report_id' => $report->id,
                'report_date' => $dateString,
                'record_count' => $report->record_count,
                'file_name' => $fileName,
                'user_id' => $generatedByUserId,
            ]);

            return $report->fresh();
        } catch (Throwable $e) {
            $report->fill([
                'generation_status' => DailyReport::STATUS_FAILED,
                'error_message' => $this->safeErrorMessage($e),
                'generated_by' => $generatedByUserId,
            ]);
            $report->save();

            Log::error('Daily visitor report generation failed.', [
                'action' => 'daily_report_generation_failed',
                'report_id' => $report->id,
                'report_date' => $dateString,
                'user_id' => $generatedByUserId,
                'error' => $e->getMessage(),
            ]);

            throw $e;
        }
    }

    /**
     * Generate a manual multi-day visitor Excel report (6:00 AM–11:59:59 PM per day).
     *
     * @param  string|\DateTimeInterface  $startDate
     * @param  string|\DateTimeInterface  $endDate
     * @param  User|int|null  $adminUser  Admin user model or user id
     */
    public function generateDateRangeReport(
        string|\DateTimeInterface $startDate,
        string|\DateTimeInterface $endDate,
        User|int|null $adminUser = null
    ): DailyReport {
        [$start, $end] = $this->normalizeDateRange($startDate, $endDate);

        $startString = $start->toDateString();
        $endString = $end->toDateString();
        $fileName = $this->buildDateRangeFileName($startString, $endString);
        $relativePath = $this->buildDateRangeRelativePath($startString, $fileName);

        $generatedByUserId = $adminUser instanceof User
            ? (int) $adminUser->getAuthIdentifier()
            : ($adminUser !== null ? (int) $adminUser : null);

        $generatedByName = $this->resolveAdminDisplayName($adminUser);

        $report = new DailyReport([
            'report_date' => $startString,
            'date_range_end' => $endString,
            'report_type' => self::DATE_RANGE_REPORT_TYPE,
            'file_name' => $fileName,
            'file_path' => $relativePath,
            'generation_status' => DailyReport::STATUS_GENERATING,
            'generated_by' => $generatedByUserId,
            'error_message' => null,
        ]);
        $report->save();

        try {
            $rows = $this->fetchVisitorRowsForDateRange($start, $end);
            $absolutePath = $this->writeDateRangeExcelFile(
                $start,
                $end,
                $rows,
                $relativePath,
                $generatedByName
            );

            if (! is_file($absolutePath)) {
                throw new RuntimeException('The Excel report file could not be saved to secure storage.');
            }

            $report->fill([
                'file_name' => $fileName,
                'file_path' => $relativePath,
                'record_count' => $rows->count(),
                'generation_status' => DailyReport::STATUS_COMPLETED,
                'generated_at' => now('Asia/Manila'),
                'generated_by' => $generatedByUserId,
                'error_message' => null,
            ]);
            $report->save();

            Log::info('Date-range visitor report generated successfully.', [
                'action' => 'date_range_report_generated',
                'report_id' => $report->id,
                'start_date' => $startString,
                'end_date' => $endString,
                'record_count' => $report->record_count,
                'file_name' => $fileName,
                'user_id' => $generatedByUserId,
                'generation_status' => DailyReport::STATUS_COMPLETED,
            ]);

            return $report->fresh();
        } catch (Throwable $e) {
            $report->fill([
                'generation_status' => DailyReport::STATUS_FAILED,
                'error_message' => $this->safeErrorMessage($e),
                'generated_by' => $generatedByUserId,
            ]);
            $report->save();

            Log::error('Date-range visitor report generation failed.', [
                'action' => 'date_range_report_generation_failed',
                'report_id' => $report->id,
                'start_date' => $startString,
                'end_date' => $endString,
                'user_id' => $generatedByUserId,
                'generation_status' => DailyReport::STATUS_FAILED,
                'error' => $e->getMessage(),
            ]);

            throw $e;
        }
    }

    public function normalizeReportDate(string|\DateTimeInterface $date): Carbon
    {
        try {
            if ($date instanceof \DateTimeInterface) {
                $reportDate = Carbon::instance(\DateTimeImmutable::createFromInterface($date))
                    ->timezone('Asia/Manila')
                    ->startOfDay();
            } else {
                $raw = trim((string) $date);
                $parsed = Carbon::createFromFormat('Y-m-d', $raw, 'Asia/Manila');

                if (! $parsed || $parsed->format('Y-m-d') !== $raw) {
                    throw new RuntimeException('Invalid report date. Please use the YYYY-MM-DD format.');
                }

                $reportDate = $parsed->startOfDay();
            }
        } catch (RuntimeException $e) {
            throw $e;
        } catch (Throwable $e) {
            throw new RuntimeException('Invalid report date. Please use the YYYY-MM-DD format.');
        }

        $today = Carbon::now('Asia/Manila')->startOfDay();

        if ($reportDate->greaterThan($today)) {
            throw new RuntimeException('Future dates are not allowed for daily visitor reports.');
        }

        return $reportDate;
    }

    /**
     * Validate and normalize a manual date-range selection (Asia/Manila).
     *
     * @return array{0: Carbon, 1: Carbon}
     */
    public function normalizeDateRange(string|\DateTimeInterface $startDate, string|\DateTimeInterface $endDate): array
    {
        $start = $this->parseCalendarDate($startDate, 'start date');
        $end = $this->parseCalendarDate($endDate, 'end date');
        $today = Carbon::now('Asia/Manila')->startOfDay();

        if ($start->greaterThan($today) || $end->greaterThan($today)) {
            throw new RuntimeException('Future dates are not allowed.');
        }

        if ($end->lt($start)) {
            throw new RuntimeException('The end date must be on or after the start date.');
        }

        $inclusiveDays = $start->diffInDays($end) + 1;
        $maxDays = (int) config('reports.max_range_days', 31);

        if ($inclusiveDays < 2) {
            throw new RuntimeException('The selected range must cover at least two days.');
        }

        if ($inclusiveDays > $maxDays) {
            throw new RuntimeException('The selected date range cannot exceed '.$maxDays.' days.');
        }

        return [$start, $end];
    }

    public function buildFileName(string $dateString): string
    {
        return 'NU-Secure_Visitor_Report_'.$this->sanitizeDateToken($dateString).'.xlsx';
    }

    public function buildDateRangeFileName(string $startDate, string $endDate): string
    {
        return 'NU-Secure_Visitor_Report_'
            .$this->sanitizeDateToken($startDate)
            .'_to_'
            .$this->sanitizeDateToken($endDate)
            .'.xlsx';
    }

    public function buildRelativePath(string $dateString, string $fileName): string
    {
        $safeName = $this->sanitizeFileName($fileName);
        $parts = explode('-', $this->sanitizeDateToken($dateString));
        $year = $parts[0] ?? date('Y');
        $month = $parts[1] ?? date('m');

        return 'reports/daily/'.$year.'/'.$month.'/'.$safeName;
    }

    public function buildDateRangeRelativePath(string $startDate, string $fileName): string
    {
        $safeName = $this->sanitizeFileName($fileName);
        $parts = explode('-', $this->sanitizeDateToken($startDate));
        $year = $parts[0] ?? date('Y');
        $month = $parts[1] ?? date('m');

        return 'reports/date-range/'.$year.'/'.$month.'/'.$safeName;
    }

    /**
     * Calendar-day fetch used by the automated / manual daily report (00:00–23:59:59).
     *
     * @return Collection<int, array<string, mixed>>
     */
    public function fetchVisitorRowsForDate(Carbon $reportDate): Collection
    {
        $start = $reportDate->copy()->timezone('Asia/Manila')->startOfDay();
        $end = $reportDate->copy()->timezone('Asia/Manila')->endOfDay();

        return $this->fetchVisitorRowsUsingWindows([
            [$start->toDateTimeString(), $end->toDateTimeString()],
        ]);
    }

    /**
     * Multi-day fetch applying 6:00 AM–11:59:59 PM independently for every selected date.
     *
     * Does not use one continuous midnight-to-midnight range, so early-morning
     * records on the second and succeeding dates are excluded.
     *
     * @return Collection<int, array<string, mixed>>
     */
    public function fetchVisitorRowsForDateRange(Carbon $startDate, Carbon $endDate): Collection
    {
        return $this->fetchVisitorRowsUsingWindows(
            $this->buildOperatingDayWindows($startDate, $endDate)
        );
    }

    /**
     * Build per-day operating windows of 6:00:00 AM–11:59:59 PM (Asia/Manila).
     *
     * @return list<array{0: string, 1: string}>
     */
    public function buildOperatingDayWindows(Carbon $startDate, Carbon $endDate): array
    {
        $start = $startDate->copy()->timezone('Asia/Manila')->startOfDay();
        $end = $endDate->copy()->timezone('Asia/Manila')->startOfDay();

        if ($end->lt($start)) {
            throw new RuntimeException('The end date must be on or after the start date.');
        }

        $hour = (int) config('reports.operating_hour_start', 6);
        $minute = (int) config('reports.operating_minute_start', 0);
        $second = (int) config('reports.operating_second_start', 0);

        $windows = [];
        $cursor = $start->copy();

        while ($cursor->lte($end)) {
            $dayStart = $cursor->copy()->setTime($hour, $minute, $second);
            $dayEnd = $cursor->copy()->setTime(23, 59, 59);
            $windows[] = [$dayStart->toDateTimeString(), $dayEnd->toDateTimeString()];
            $cursor->addDay();
        }

        return $windows;
    }

    /**
     * Build spreadsheet content for the given rows (public for unit testing).
     *
     * @param  Collection<int, array<string, mixed>>  $rows
     */
    public function buildSpreadsheet(Carbon $reportDate, Collection $rows): Spreadsheet
    {
        $spreadsheet = new Spreadsheet;
        $sheet = $spreadsheet->getActiveSheet();
        $sheet->setTitle('Daily Visitors');

        $lastColumn = 'S';

        $sheet->setCellValue('A1', 'NU-Secure Daily Visitor Report');
        $sheet->mergeCells('A1:'.$lastColumn.'1');
        $sheet->getStyle('A1')->getFont()->setBold(true)->setSize(16);
        $sheet->getStyle('A1')->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);

        $sheet->setCellValue('A2', 'Report Date: '.$reportDate->format('F j, Y'));
        $sheet->mergeCells('A2:'.$lastColumn.'2');
        $sheet->getStyle('A2')->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);

        $this->writeVisitorTable($sheet, $rows, 4, $lastColumn);

        return $spreadsheet;
    }

    /**
     * Build a date-range workbook with operating-hours metadata.
     *
     * @param  Collection<int, array<string, mixed>>  $rows
     */
    public function buildDateRangeSpreadsheet(
        Carbon $startDate,
        Carbon $endDate,
        Collection $rows,
        string $generatedByName = '',
        ?Carbon $generatedAt = null
    ): Spreadsheet {
        $spreadsheet = new Spreadsheet;
        $sheet = $spreadsheet->getActiveSheet();
        $sheet->setTitle('Date-Range Visitors');

        $lastColumn = 'S';
        $generatedAt = $generatedAt?->copy()->timezone('Asia/Manila') ?? now('Asia/Manila');

        $sheet->setCellValue('A1', 'NU-Secure Visitor Date-Range Report');
        $sheet->mergeCells('A1:'.$lastColumn.'1');
        $sheet->getStyle('A1')->getFont()->setBold(true)->setSize(16);
        $sheet->getStyle('A1')->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);

        $meta = [
            2 => 'Start Date: '.$startDate->format('F j, Y'),
            3 => 'End Date: '.$endDate->format('F j, Y'),
            4 => 'Reporting Schedule: 6:00 AM to 11:59 PM per day',
            5 => 'Generated At: '.$generatedAt->format('F j, Y g:i:s A').' (Asia/Manila)',
            6 => 'Generated By: '.($generatedByName !== '' ? $generatedByName : 'Admin'),
        ];

        foreach ($meta as $row => $label) {
            $sheet->setCellValue('A'.$row, $label);
            $sheet->mergeCells('A'.$row.':'.$lastColumn.$row);
            $sheet->getStyle('A'.$row)->getAlignment()->setHorizontal(Alignment::HORIZONTAL_CENTER);
        }

        $this->writeVisitorTable($sheet, $rows, 8, $lastColumn);

        return $spreadsheet;
    }

