<?php

namespace App\Console\Commands;

use Illuminate\Console\Command;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Schema;
use Illuminate\Support\Facades\Storage;

class InspectDailyReports extends Command
{
    protected $signature = 'reports:inspect-daily';

    protected $description = 'Read report metadata, scheduler configuration, queue counts and stored file counts without generating reports';

    public function handle(): int
    {
        $this->line('Application timezone: '.config('app.timezone'));
        $this->line('Report timezone: Asia/Manila');
        $this->line('Database driver: '.DB::getDriverName());
        $this->line('Cache store: '.config('cache.default'));
        $this->line('Queue connection: '.config('queue.default'));
        $this->line('Daily uniqueness migration applied: '.(Schema::hasColumn('daily_reports', 'daily_scope_id') ? 'yes' : 'no'));

        if (DB::getDriverName() === 'pgsql') {
            $this->line('PostgreSQL session timezone: '.DB::selectOne('SHOW TIMEZONE')->TimeZone);
            $this->table(['Table', 'Column', 'Type'], DB::table('information_schema.columns')
                ->select('table_name', 'column_name', 'data_type')
                ->where('table_schema', 'public')
                ->whereIn('table_name', ['daily_reports', 'visit', 'office_scan'])
                ->whereIn('column_name', ['report_date', 'created_at', 'generated_at', 'entry_time', 'scan_time'])
                ->orderBy('table_name')->orderBy('column_name')
                ->get()->map(fn ($row) => (array) $row)->all());
        }

        $this->table(['Type', 'Office', 'First date', 'Last date', 'First creation (DB)', 'Last creation (DB)'], DB::table('daily_reports')
            ->select('report_type', 'office_id')
            ->selectRaw('MIN(report_date) AS first_date, MAX(report_date) AS last_date, MIN(created_at) AS first_created, MAX(created_at) AS last_created')
            ->groupBy('report_type', 'office_id')->orderBy('report_type')->orderBy('office_id')
            ->get()->map(fn ($row) => (array) $row)->all());

        $this->table(['Type', 'Office', 'Status', 'Count'], DB::table('daily_reports')
            ->select('report_type', 'office_id', 'generation_status')
            ->selectRaw('COUNT(*) AS report_count')
            ->groupBy('report_type', 'office_id', 'generation_status')
            ->orderBy('report_type')->orderBy('office_id')
            ->get()->map(fn ($row) => (array) $row)->all());

        $this->table(['ID', 'Date', 'Type', 'Office', 'Status', 'Generated by', 'Created at (DB)', 'Generated at (DB)'], DB::table('daily_reports')
            ->select('id', 'report_date', 'report_type', 'office_id', 'generation_status', 'generated_by', 'created_at', 'generated_at')
            ->orderByDesc('id')->limit(30)->get()->map(fn ($row) => (array) $row)->all());

        foreach (['jobs', 'failed_jobs'] as $table) {
            if (Schema::hasTable($table)) {
                $this->line($table.' total: '.DB::table($table)->count());
                $this->line($table.' payloads mentioning reports (candidates only): '.DB::table($table)
                    ->whereRaw('LOWER(payload) LIKE ?', ['%report%'])->count());
            }
        }

        $this->line('Private daily report files: '.count(Storage::disk('local')->allFiles('reports/daily')));
        $this->line('Private date-range report files: '.count(Storage::disk('local')->allFiles('reports/date-range')));
        $this->info('Read-only inspection complete. No reports or visitor records were generated, changed or deleted.');

        return self::SUCCESS;
    }
}
