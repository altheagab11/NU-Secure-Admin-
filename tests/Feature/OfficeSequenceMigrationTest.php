<?php

namespace Tests\Feature;

use App\Models\Office;
use Illuminate\Database\UniqueConstraintViolationException;
use Illuminate\Support\Facades\DB;
use Tests\TestCase;

class OfficeSequenceMigrationTest extends TestCase
{
    protected function setUp(): void
    {
        parent::setUp();

        if (! getenv('OFFICE_SEQUENCE_TESTS') || DB::connection()->getDriverName() !== 'pgsql') {
            $this->markTestSkipped('Enable OFFICE_SEQUENCE_TESTS with a PostgreSQL connection to test identity sequences.');
        }

        DB::beginTransaction();
        // A session-local table shadows the directory without changing real records.
        DB::statement('CREATE TEMPORARY TABLE office (office_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, office_name VARCHAR(150), room_number VARCHAR(30), floor VARCHAR(100), is_active BOOLEAN) ON COMMIT DROP');
        DB::table('office')->insert([
            ['office_id' => 1, 'office_name' => 'First Office'],
            ['office_id' => 2, 'office_name' => 'Second Office'],
            ['office_id' => 10, 'office_name' => 'Imported Office'],
        ]);
    }

    protected function tearDown(): void
    {
        while (DB::transactionLevel() > 0) {
            DB::rollBack();
        }

        parent::tearDown();
    }

    private function migration(): object
    {
        return require database_path('migrations/2026_10_19_020000_sync_office_id_sequence.php');
    }

    public function test_imported_ids_cause_a_collision_until_the_sequence_is_synchronized(): void
    {
        try {
            DB::transaction(fn () => Office::create(['office_name' => 'Before repair']));
            $this->fail('The stale identity sequence should collide with an imported ID.');
        } catch (UniqueConstraintViolationException $exception) {
            $this->assertSame('23505', $exception->errorInfo[0]);
        }

        $this->migration()->up();

        $office = Office::create(['office_name' => 'New Office', 'room_number' => 'G-03', 'floor' => 'Ground Floor', 'is_active' => true]);
        $this->assertSame(11, $office->office_id);
        $this->assertSame(4, Office::count());
        $this->assertSame('Imported Office', Office::findOrFail(10)->office_name);
    }

    public function test_sequence_ahead_of_existing_records_is_never_rewound(): void
    {
        DB::selectOne("SELECT setval(pg_get_serial_sequence('office', 'office_id'), 50, true)");

        $this->migration()->up();

        $this->assertSame(51, Office::create(['office_name' => 'New Office'])->office_id);
    }

    public function test_repeated_migration_and_rollback_keep_office_ids_safe(): void
    {
        $migration = $this->migration();
        $migration->up();
        $this->assertSame(11, Office::create(['office_name' => 'New Office'])->office_id);
        $migration->up();
        $migration->down();

        $this->assertSame(12, Office::create(['office_name' => 'Another Office'])->office_id);
    }
}
